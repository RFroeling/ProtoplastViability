import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.axes import Axes
from tkinter import filedialog
from typing import Any


def select_working_directory():
    """Opens selection window to select the working directory. Should be the same path as used in the FIJI macro.

    Working directory should contain "01_analysis/viability.csv".

    Returns:
        string: Path to working directory.
    """
    return filedialog.askdirectory(title="Select Working Directory")


def initialize_paths(working_dir: str):
    """Initializes input and output paths for saving results.

    Args:
        working_dir (str): Path to working directory.
        
    Returns:
        tuple: input_path, viability_output_path, stats_output_path, plot_output_path

    Raises:
        ValueError: If the input file does not exist.
    """
    input_path = os.path.join(working_dir, '01_analysis', 'summary.csv')
    if not os.path.exists(input_path):
        raise ValueError(f"File not found: {input_path}")

    viability_output_path = os.path.join(working_dir, '01_analysis/viability.csv')
    stats_output_path = os.path.join(working_dir, '01_analysis/viability_statistics.csv')
    plot_output_path = os.path.join(working_dir, '01_analysis/viability_plot.png')
    
    return input_path, viability_output_path, stats_output_path, plot_output_path


def load_data(file_path: str) -> pd.DataFrame:
    """Loads the summary CSV file generated by the FIJI macro.

    Args:
        file_path (str): Path to the summary CSV file.

    Returns:
        pd.DataFrame: DataFrame containing the summary data.
    """
    return pd.read_csv(file_path)


def calculate_viability(bf_row: pd.Series, fda_row: pd.Series) -> float:
    """Calculates viability of a single BF/FDA pair.

    *Viability = (FDA cell count / BF cell count) x 100%*

    Args:
        bf_row (pd.Series): Brightfield row extracted from DataFrame containing summary data.
        fda_row (pd.Series): Corresponding FDA row.

    Returns:
        float: Viability
    """
    bf_count = bf_row['Count']
    fda_count = fda_row['Count'].values[0]

    return (fda_count / bf_count) * 100


def viability_per_sample(df):
    """Calculates viability of all sample-entries in the summary DataFrame.

    Assumes replicates are indicated by the suffix (_00x), where x indicates the index of that replicate (so _001, _002, etc.). 

    Args:
        df (pd.DataFrame): DataFrame containing the summary output from the FIJI macro.

    Returns:
        pd.DataFrame: DataFrame containing the calculated viability for each image (BF/FDA pair).
    """
    results = [] # Initialize list to hold viability data
    
    bf_rows = df[df['Slice'].str.endswith('_BF')]
    fda_rows = df[df['Slice'].str.endswith('_FDA')]
    
    for _, bf_row in bf_rows.iterrows():
        slice_prefix = bf_row['Slice'].replace('_BF', '')      
        fda_row = fda_rows[fda_rows['Slice'].str.startswith(slice_prefix)] # Find the corresponding FDA row
        
        if not fda_row.empty:
            viability = calculate_viability(bf_row, fda_row)
            condition = slice_prefix.rsplit("_", 1)[0] # Extract condition (everything before "_00x")
            results.append({
                'Slice Prefix': slice_prefix,
                'Condition': condition,
                'Viability': viability
            })

    viability_df = pd.DataFrame(results)
    print(viability_df)

    return viability_df


def calculate_statistics(df: pd.DataFrame):
    """Groups viability data by condition and calculates mean, sample size and standard deviation.

    Args:
        df (pd.DataFrame): DataFrame containing viability data per image

    Returns:
        pd.DataFrame: DataFrame containing calculated statistics per condition.
    """
    stats = df.groupby('Condition')['Viability'].agg(
        Mean='mean',
        Count='count',
        StdDev='std'
    ).reset_index()
    
    return stats


def initialize_plot(df: pd.DataFrame) -> tuple:
    """Initializes the plot for viability data.

    Args:
        df (pd.DataFrame): DataFrame containing viability data per image.

    Returns:
        tuple: fig, ax, conditions, data
    """
    grouped = df.groupby("Condition")["Viability"].apply(list)
    conditions = grouped.index
    data = grouped.values

    fig, ax = plt.subplots(figsize=(5, 8))

    return fig, ax, conditions, data


def plot_boxplot(ax: Axes, data: list):
    """Plots a boxplot on the given Axes.

    Args:
        ax (Axes): Matplotlib Axes to plot on.
        data (list): List of lists containing viability data per condition.
    """
    bp = ax.boxplot(data, patch_artist=True, widths=0.6)
    for patch in bp['boxes']:
        patch.set_facecolor("#548235")
        patch.set_alpha(0.6)


def plot_violin(ax: Axes, data: list):
    """Plots a violin plot on the given Axes.
    
    Args:
        ax (Axes): Matplotlib Axes to plot on.
        data (list): List of lists containing viability data per condition.
    """
    parts: Any = ax.violinplot(data, showmeans=True, showextrema=False)
    parts['cmeans'].set_color('black')  # Set mean line color
    for pc in parts.get('bodies', []):
        pc.set_facecolor('#548235')
        pc.set_edgecolor('black')
        pc.set_alpha(0.6)


def plot_viability(df, plot_type="box", save_path=None):
    """Plots viability data as either a boxplot or violin plot with individual data points and mean ± std annotations.

    Args:
        df (pd.DataFrame): DataFrame containing viability data per image.  
        plot_type (str, optional): Type of plot to create ("violin" or "box"). Defaults to "box".
        save_path (str, optional): Path to save the plot image. Defaults to None.

    Raises:
        ValueError: If plot_type is not "violin" or "box".
    """
    if plot_type not in ["violin", "box"]:
        raise ValueError("plot_type must be 'violin' or 'box'")
    
    fig, ax, conditions, data = initialize_plot(df)

    if plot_type == "violin":
        plot_violin(ax, data)
    elif plot_type == "box":
        plot_boxplot(ax, data)
    
    for i, values in enumerate(data, start=1):
        # Plot individual data points with jitter
        x = np.random.normal(i, 0.04, size=len(values))  # jitter
        ax.scatter(x, values, color='black', alpha=0.7, s=20, zorder=3)
        # Annotate mean ± std
        mean_val = np.mean(values)
        std_val = np.std(values)
        ax.text(i, mean_val + std_val + 2, f"{mean_val:.1f} ± {std_val:.1f}",
                ha='center', va='bottom', fontsize=9, fontweight='bold')
        
    # Extend y-axis so annotations fit
    max_val = max([max(values) for values in data])
    ax.set_ylim(top=max_val * 1.025)  # 2.5% higher than max datapoint

    # Formatting
    ax.set_xticks(range(1, len(conditions) + 1))
    ax.set_xticklabels(conditions, rotation=45, ha="right")
    ax.set_ylabel("Viability (%)")

    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=300)
    plt.show()


def main():
    """Main function to execute the viability analysis workflow."""
    working_dir = select_working_directory()
    if not working_dir:
        print("No directory selected. Exiting...")

    paths = initialize_paths(working_dir)

    summary_df = load_data(paths[0])
    viability_df = viability_per_sample(summary_df)

    # Calculate statistics for each condition
    stats_df = calculate_statistics(viability_df)

    viability_df.to_csv(paths[1], index=False)
    stats_df.to_csv(paths[2], index=False)

    # Plot the statistics
    plot_viability(viability_df, plot_type='box', save_path=paths[3])
    print(f"Viability results saved to: {paths[1]}")
    print(f"Statistics saved to: {paths[2]}")
    print(f"Plot saved to: {paths[3]}")

# ========== Execution ==========
if __name__ == "__main__":
    main()